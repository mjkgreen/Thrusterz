// Writes World 4's levels into js/levels.js (between the WORLD 4 markers)
// from the chapter files tools/w4/ch1.js … ch5.js, which stay the source:
// each chapter keeps its levels next to their proofs and naive "fails".
//   node tools/w4/build.js          (npm run build:w4)
//   node tools/w4/build.js --check  exit 1 if js/levels.js is out of date
'use strict';
const fs = require('fs');
const path = require('path');

const CHAPTERS = [
  { file: 'ch1', name: 'Sunburn' },
  { file: 'ch2', name: 'Shadows and Beams' },
  { file: 'ch3', name: 'Shadow Lanes' },
  { file: 'ch4', name: 'Deep Gravity' },
  { file: 'ch5', name: 'Grand Missions' },
];
const BEGIN = '  // ---- BEGIN WORLD 4 (generated by tools/w4/build.js from tools/w4/ch*.js; edit those) ----';
const END = '  // ---- END WORLD 4 ----';

function generate() {
  const out = [BEGIN, '  const WORLD4 = ['];
  for (const ch of CHAPTERS) {
    out.push(`    // Chapter: ${ch.name}`);
    for (const L of require('./' + ch.file).levels) {
      const json = JSON.stringify(L, null, 2).split('\n').map(s => '    ' + s).join('\n');
      out.push(json + ',');
    }
  }
  out.push('  ];', '  for (const L of WORLD4) L.world = 4;', '  LEVELS.push(...WORLD4);', END);
  return out.join('\n');
}

const file = path.join(__dirname, '..', '..', 'js', 'levels.js');
const src = fs.readFileSync(file, 'utf8');
const a = src.indexOf(BEGIN), b = src.indexOf(END);
if (a < 0 || b < 0) { console.error('WORLD 4 markers not found in js/levels.js'); process.exit(2); }
const next = src.slice(0, a) + generate() + src.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== src) { console.error('js/levels.js is out of date: run npm run build:w4'); process.exit(1); }
  console.log('js/levels.js World 4 is up to date');
} else {
  fs.writeFileSync(file, next);
  console.log('wrote World 4 into js/levels.js');
}
